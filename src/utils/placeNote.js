/* תחנות שהסימון שלהן על המפה אינו המיקום האמיתי.

   גולש שאל למה "מצרים" במסע של אברהם מצוירת במדבר סיני. התשובה היא
   שמסגרת המפה אינה מגיעה לנילוס, ולכן הנקודה הוצבה בקצה הדרום-מערבי -
   מציין כיוון ולא מיקום. בלי לומר זאת, המפה טוענת טענה שגויה.

   שתי סיבות שונות, ולכן שני נוסחים:
     מחוץ למפה          - המקום מחוץ למסגרת המפה. הנקודה מציינת כיוון.
     זיהוי שנוי במחלוקת - המקום בתחום המפה, אך זיהויו אינו מוסכם במקורות.

   ההערה מוצגת ברשימת התחנות ובכרטיס המסע. על המפה עצמה (אוקטובר 2026)
   מקום מחוץ למסגרת אינו נקודה על היבשה אלא חץ בשולי המפה לכיוונו - ראו
   OFFMAP למטה. גולש העיר ש"מצרים זה לא סיני, גם לא בקירוב": ההערה ברשימה
   לא הספיקה, כי על המפה הנקודה ישבה על החוף הצפוני של סיני.

   המפתח הוא שם התחנה ולא זוג (מסע, תחנה): "מצרים" חוזרת בתשעה מסעות
   שונים, וצריך לומר עליה את אותו הדבר בכולם. */

const APPROX = new Set([
  'מצרים',
  'גושן (מצרים)',
  'ארץ גושן',
  'היאור (מצרים)',
  'אור כשדים',
  'חרן',
  'מדין',
  'חרן (פדן ארם)',
  'חרן - הבאר',
  'ארם נהריים (חרן)',
  'בבל',
  'בבל (דרך רבלה)',
  'נהר כבר (בבל)',
  'נינוה',
  'שושן הבירה',
  'אשור (חלח, חבור, גוזן וערי מדי)',
]);

const DISPUTED = new Set([
  'הר סיני',
  'הר חורב',
  'הר האלוקים (חורב)',
  'ים סוף',
]);

/* לאיזה צד של המפה כל מקום שמחוץ למסגרת. התחנה נדחפת לשוליים באותו צד
   (journeyStations), ומצוירת שם עם חץ החוצה ושם המקום. הכיוון הוא הכיוון
   האמיתי מארץ ישראל, ולא המקום שבו הנקודה נחתה קודם: בבל נחתה בראש
   המפה כי ההיטל הישן קיצץ אותה, אבל היא במזרח. המפתחות = APPROX. */
const OFFMAP = {
  'מצרים': 'w', 'גושן (מצרים)': 'w', 'ארץ גושן': 'w', 'היאור (מצרים)': 'w',
  'אור כשדים': 'e', 'בבל': 'e', 'בבל (דרך רבלה)': 'e', 'נהר כבר (בבל)': 'e', 'שושן הבירה': 'e',
  'חרן': 'n', 'חרן (פדן ארם)': 'n', 'חרן - הבאר': 'n', 'ארם נהריים (חרן)': 'n',
  'נינוה': 'n', 'אשור (חלח, חבור, גוזן וערי מדי)': 'n',
  'מדין': 's',
};

/* קו הרוחב האמיתי של מקומות במערב. בלי זה הגובה בשוליים נקבע לפי המקום
   שבו הנקודה הישנה נחתה, ומצרים, גושן והיאור ישבו בשולי הים התיכון - כאילו
   הם בים. עכשיו כל אחד יושב בשוליים בגובה שלו באמת, ומה שדרומי מתחתית
   המפה (מצרים) נצמד לפינה. מצרים = נוף (ממפיס), גושן = ואדי טומילאת,
   היאור = זרועות הדלתא ליד צוען ("שדה צוען", תהלים עח). */
const OFFMAP_LAT = {
  'מצרים': 29.85, 'גושן (מצרים)': 30.55, 'ארץ גושן': 30.55, 'היאור (מצרים)': 30.98,
};

/** @returns {number|null} קו הרוחב האמיתי של מקום מחוץ למסגרת, אם ידוע */
export const offMapLat = (name) => OFFMAP_LAT[String(name || '').trim()] ?? null;

/** @returns {'n'|'s'|'e'|'w'|null} הצד של המפה שאליו המקום יוצא, או null אם הוא בתוך המסגרת */
export const offMapDir = (name) => OFFMAP[String(name || '').trim()] || null;

/* השם הקצר, בלי הסוגריים ובלי התוספת אחרי המקף: על המפה "גושן (מצרים)"
   ארוך מדי לשוליים, והחץ כבר אומר לאן. השם צמוד לעיגול מבפנים, והחץ הוא
   צורה בצד החיצוני של העיגול - לא תו בתוך השם, שישב בין העיגול לשם */
export const offMapName = (name) => String(name).replace(/\s*\(.*\)\s*$/, '').replace(/\s*-.*$/, '').trim();

/** @returns {string|null} נוסח ההערה, או null אם התחנה מדויקת */
export function stationNote(name) {
  if (APPROX.has(name)) return 'מחוץ למפה';
  if (DISPUTED.has(name)) return 'זיהוי שנוי במחלוקת';
  return null;
}


/* שבעה משמות התחנות כבר מכילים סוגריים - "גושן (מצרים)", "חרן (פדן ארם)".
   הוספת סוגריים נוספים עליהם נותנת "גושן (מצרים) (מחוץ למפה)", ולכן שם
   ההערה מופרדת בנקודה במקום. */
export function stationNoteText(name) {
  const note = stationNote(name);
  if (!note) return null;
  return name.trim().endsWith(')') ? ` · ${note}` : ` (${note})`;
}