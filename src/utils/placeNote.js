/* תחנות שהסימון שלהן על המפה אינו המיקום האמיתי.

   גולש שאל למה "מצרים" במסע של אברהם מצוירת במדבר סיני. התשובה היא
   שמסגרת המפה אינה מגיעה לנילוס, ולכן הנקודה הוצבה בקצה הדרום-מערבי -
   מציין כיוון ולא מיקום. בלי לומר זאת, המפה טוענת טענה שגויה.

   שתי סיבות שונות, ולכן שני נוסחים:
     מיקום מקורב        - המקום מחוץ למסגרת המפה. הנקודה מציינת כיוון.
     זיהוי שנוי במחלוקת - המקום בתחום המפה, אך זיהויו אינו מוסכם במקורות.

   ההערה מוצגת ברשימת התחנות ובכרטיס המסע בלבד - לא על גבי המפה, כדי
   לא להעמיס על התוויות.

   המפתח הוא שם התחנה ולא זוג (מסע, תחנה): "מצרים" חוזרת בתשעה מסעות
   שונים, וצריך לומר עליה את אותו הדבר בכולם. */

const APPROX = new Set([
  'מצרים',
  'גושן (מצרים)',
  'היאור (מצרים)',
  'אור כשדים',
  'חרן',
  'חרן (פדן ארם)',
  'חרן - הבאר',
  'ארם נהריים (חרן)',
  'בבל',
  'בבל (דרך רבלה)',
  'נהר כבר (בבל)',
  'נינוה',
  'שושן הבירה',
  'אשור (חלח, חבור, גוזן וערי מדי)',
]);

const DISPUTED = new Set([
  'הר סיני',
  'הר חורב',
  'הר האלוקים (חורב)',
  'מדין וחורב',
  'ים סוף',
]);

/** @returns {string|null} נוסח ההערה, או null אם התחנה מדויקת */
export function stationNote(name) {
  if (APPROX.has(name)) return 'מיקום מקורב';
  if (DISPUTED.has(name)) return 'זיהוי שנוי במחלוקת';
  return null;
}


/* שבעה משמות התחנות כבר מכילים סוגריים - "גושן (מצרים)", "חרן (פדן ארם)".
   הוספת סוגריים נוספים עליהם נותנת "גושן (מצרים) (מיקום מקורב)", ולכן שם
   ההערה מופרדת בנקודה במקום. */
export function stationNoteText(name) {
  const note = stationNote(name);
  if (!note) return null;
  return name.trim().endsWith(')') ? ` · ${note}` : ` (${note})`;
}