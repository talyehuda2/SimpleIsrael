--  בעתיד חייבת להתחיל ב-admin:, אחרת היא ציבורית כברירת מחדל.
--  זו ההנחה שהמדיניות הזאת נשענת עליה, ולכן היא כתובה כאן במפורש.
--
--  להריץ פעם אחת ב-Supabase: SQL Editor -> New query -> הדבקה -> Run
